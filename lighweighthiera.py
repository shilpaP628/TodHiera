for train_idx, val_idx in skf.split(np.zeros(len(full_dataset_for_split)), full_dataset_for_split.labels):
    print(f"\n{'='*70}")
    print(f"========== Fold {fold}/{NUM_FOLDS} ==========")
    print(f"{'='*70}")

    train_dataset = ActivityDataset(DATA_DIR, CLASSES_LIST, SEQUENCE_LENGTH, IMAGE_HEIGHT, is_train=True)
    val_dataset   = ActivityDataset(DATA_DIR, CLASSES_LIST, SEQUENCE_LENGTH, IMAGE_HEIGHT, is_train=False)

