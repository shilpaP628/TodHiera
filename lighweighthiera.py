def create_reduced_hiera_with_partial_pretrained(
    num_classes=16,
    stages=(2, 3, 10, 3),
    embed_dim=96,
    device="cuda"
):
    model = hiera.Hiera(
        input_size=(16, 224, 224),
        in_chans=3,
        embed_dim=embed_dim,
        num_heads=1,
        num_classes=num_classes,
        stages=stages,
        q_pool=3,
        q_stride=(1, 2, 2),
        mask_unit_size=(1, 8, 8),
        patch_kernel=(3, 7, 7),
        patch_stride=(2, 4, 4),
        patch_padding=(1, 3, 3),
        sep_pos_embed=True,
        drop_path_rate=0.15,
    )

    print("\nLoading original pretrained Hiera-Base weights...")
    pretrained = hiera.hiera_base_16x224(
        pretrained=True,
        checkpoint="mae_k400_ft_k400",
        num_classes=400
    )
    pretrained_dict = pretrained.state_dict()
    model_dict = model.state_dict()

    new_state_dict = OrderedDict()
    loaded_keys = []
    skipped_keys = []

    for key, value in pretrained_dict.items():
        if "head" in key:
            skipped_keys.append(key)
            continue

        if "blocks" in key:
            parts = key.split(".")
            block_idx = int(parts[1])

            if block_idx <= 4:
                new_block_idx = block_idx
            elif 5 <= block_idx <= 14:
                new_block_idx = block_idx
            elif block_idx >= 21:
                new_block_idx = block_idx - 6
            else:
                skipped_keys.append(key)
                continue

            new_key = key.replace(f"blocks.{block_idx}.", f"blocks.{new_block_idx}.")

            if new_key in model_dict and model_dict[new_key].shape == value.shape:
                new_state_dict[new_key] = value
                loaded_keys.append(new_key)
            else:
                skipped_keys.append(key)
        else:
            if key in model_dict and model_dict[key].shape == value.shape:
                new_state_dict[key] = value
                loaded_keys.append(key)
            else:
                skipped_keys.append(key)

    missing, unexpected = model.load_state_dict(new_state_dict, strict=False)

    print("\n" + "="*65)
    print("PARTIAL WEIGHT LOADING SUMMARY")
    print("="*65)
    print(f"Successfully loaded keys : {len(loaded_keys)}")
    print(f"Skipped keys             : {len(skipped_keys)}")
    print(f"Missing keys             : {len(missing)}")
    print(f"Unexpected keys          : {len(unexpected)}")
    print("="*65)

    return model.to(device)


