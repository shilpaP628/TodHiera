def train_one_epoch(model, loader, criterion, optimizer, scaler):
    model.train()
    total_loss, correct, total = 0.0, 0, 0

    for videos, labels, _ in tqdm(loader, desc=" train", leave=False):
        videos = videos.to(DEVICE, non_blocking=True)
        labels = labels.to(DEVICE, non_blocking=True)
        videos = videos.permute(0, 2, 1, 3, 4).contiguous()

        optimizer.zero_grad(set_to_none=True)

        with torch.amp.autocast('cuda', enabled=USE_AMP):
            logits = model(videos)
            loss = criterion(logits, labels)

        scaler.scale(loss).backward()
        scaler.unscale_(optimizer)
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
        scaler.step(optimizer)
        scaler.update()

        total_loss += loss.item() * videos.size(0)
        preds = logits.argmax(1)
        correct += (preds == labels).sum().item()
        total += videos.size(0)

    return total_loss / total, correct / total


@torch.no_grad()
def evaluate(model, loader, criterion):
    model.eval()
    total_loss = 0.0
    all_preds, all_labels, all_probs, all_paths = [], [], [], []

    for videos, labels, paths in tqdm(loader, desc=" val", leave=False):
        videos = videos.to(DEVICE, non_blocking=True)
        labels = labels.to(DEVICE, non_blocking=True)
        videos = videos.permute(0, 2, 1, 3, 4).contiguous()

        with torch.amp.autocast('cuda', enabled=USE_AMP):
            logits = model(videos)
            loss = criterion(logits, labels)

        total_loss += loss.item() * videos.size(0)
        probs = torch.softmax(logits.float(), dim=1)
        preds = logits.argmax(1)

        all_preds.extend(preds.cpu().numpy())
        all_labels.extend(labels.cpu().numpy())
        all_probs.extend(probs.cpu().numpy())
        all_paths.extend(paths)

    return (total_loss / len(loader.dataset),
            np.array(all_preds),
            np.array(all_labels),
            np.array(all_probs),
            all_paths)


def plot_cm(cm, title, normalize=True):
    if normalize:
        cm_plot = cm.astype("float") / (cm.sum(axis=1)[:, np.newaxis] + 1e-8)
        fmt = ".2f"
    else:
        cm_plot = cm
        fmt = "d"

    plt.figure(figsize=(12, 10))
    sns.heatmap(cm_plot, annot=True, fmt=fmt, cmap="Blues",
                xticklabels=CLASSES_LIST, yticklabels=CLASSES_LIST)
    plt.xlabel("Predicted")
    plt.ylabel("True")
    plt.title(title)
    plt.xticks(rotation=45, ha="right")
    plt.yticks(rotation=0)
    plt.tight_layout()
    plt.show()


