def freeze_early_blocks(model, train_last_percent=TRAIN_LAST_PERCENT):
    for param in model.parameters():
        param.requires_grad = False

    for param in model.head.parameters():
        param.requires_grad = True

    if hasattr(model, "blocks"):
        blocks = model.blocks
        num_blocks = len(blocks)
        num_to_train = max(1, int(num_blocks * train_last_percent))
        start_idx = num_blocks - num_to_train

        print(f"\n[Freeze Strategy] Total blocks: {num_blocks}")
        print(f"[Freeze Strategy] Training last {num_to_train} blocks "
              f"({train_last_percent*100:.0f}%) → blocks[{start_idx}:]")

        for i in range(start_idx, num_blocks):
            for param in blocks[i].parameters():
                param.requires_grad = True
    else:
        for param in model.parameters():
            param.requires_grad = True

    total = sum(p.numel() for p in model.parameters())
    trainable = sum(p.numel() for p in model.parameters() if p.requires_grad)
    print(f"[Freeze Strategy] Trainable params: {trainable:,} / {total:,} "
          f"({100 * trainable / total:.1f}%)")


