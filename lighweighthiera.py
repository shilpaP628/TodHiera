class VideoAugmentation:
    def __init__(self, size=224, is_train=True):
        self.size = size
        self.is_train = is_train
        self.normalize = transforms.Normalize(
            mean=[0.485, 0.456, 0.406],
            std=[0.229, 0.224, 0.225]
        )

    def __call__(self, frames):
        pil_frames = [transforms.ToPILImage()(f) for f in frames]

        if self.is_train:
            if random.random() < 0.5:
                pil_frames = [TF.hflip(f) for f in pil_frames]

            brightness = random.uniform(0.8, 1.2)
            contrast   = random.uniform(0.8, 1.2)
            saturation = random.uniform(0.8, 1.2)
            hue        = random.uniform(-0.05, 0.05)

            pil_frames = [TF.adjust_brightness(f, brightness) for f in pil_frames]
            pil_frames = [TF.adjust_contrast(f, contrast) for f in pil_frames]
            pil_frames = [TF.adjust_saturation(f, saturation) for f in pil_frames]
            pil_frames = [TF.adjust_hue(f, hue) for f in pil_frames]

        tensors = []
        for f in pil_frames:
            f = TF.resize(f, [self.size, self.size])
            t = TF.to_tensor(f)
            if self.is_train and random.random() < 0.3:
                noise = torch.randn_like(t) * 0.02
                t = torch.clamp(t + noise, 0.0, 1.0)
            t = self.normalize(t)
            tensors.append(t)

        return torch.stack(tensors)


def load_video_frames_raw(video_path, num_frames=16):
    container = av.open(video_path)
    frames = []
    for frame in container.decode(video=0):
        img = frame.to_ndarray(format="rgb24")
        frames.append(img)
    container.close()

    if len(frames) == 0:
        return None

    indices = np.linspace(0, len(frames) - 1, num_frames).astype(int)
    return [frames[i] for i in indices]


