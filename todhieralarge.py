fold = 1
for train_idx, val_idx in skf.split(np.zeros(len(full_dataset_for_split)), full_dataset_for_split.labels):
    print(f"\n{'='*70}")
    print(f"========== Fold {fold}/{NUM_FOLDS} ==========")
    print(f"{'='*70}")

    # ---------- Create train / val datasets with correct augmentation ----------
    train_dataset = ActivityDataset(
        DATA_DIR, CLASSES_LIST, SEQUENCE_LENGTH, IMAGE_HEIGHT, is_train=True
    )
    val_dataset = ActivityDataset(
        DATA_DIR, CLASSES_LIST, SEQUENCE_LENGTH, IMAGE_HEIGHT, is_train=False
    )

    train_subset = Subset(train_dataset, train_idx)
    val_subset   = Subset(val_dataset,   val_idx)

    # ---------- Compute class weights using ONLY training labels ----------
    train_labels = full_dataset_for_split.labels[train_idx]
    class_weights = compute_class_weight(
        "balanced",
        classes=np.unique(train_labels),
        y=train_labels
    )
    class_weight_tensor = torch.tensor(class_weights, dtype=torch.float).to(DEVICE)
    print("Class weights (this fold):", dict(enumerate(np.round(class_weights, 3))))

    train_loader = DataLoader(
        train_subset, batch_size=BATCH_SIZE, shuffle=True,
        num_workers=NUM_WORKERS, collate_fn=collate_fn,
        pin_memory=PIN_MEMORY, persistent_workers=True if NUM_WORKERS > 0 else False
    )
    val_loader = DataLoader(
        val_subset, batch_size=BATCH_SIZE, shuffle=False,
        num_workers=NUM_WORKERS, collate_fn=collate_fn,
        pin_memory=PIN_MEMORY, persistent_workers=True if NUM_WORKERS > 0 else False
    )

    model = create_hiera_model()
    criterion = nn.CrossEntropyLoss(weight=class_weight_tensor)

    # Differential learning rates
    backbone_params = [p for n, p in model.named_parameters() if "head" not in n and p.requires_grad]
    head_params     = [p for n, p in model.named_parameters() if "head" in n and p.requires_grad]

    optimizer = torch.optim.AdamW([
        {"params": backbone_params, "lr": LR_BACKBONE},
        {"params": head_params,     "lr": LR_HEAD}
    ], weight_decay=WEIGHT_DECAY)

    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=EPOCHS)
    scaler = torch.amp.GradScaler('cuda', enabled=USE_AMP)

    best_f1 = 0.0
    best_state = None
    epochs_no_improve = 0

    for epoch in range(EPOCHS):
        train_loss, train_acc = train_one_epoch(model, train_loader, criterion, optimizer, scaler)
        val_loss, y_pred, y_true, y_prob, _ = evaluate(model, val_loader, criterion)
        scheduler.step()

        # ---------- LR logging ----------
        current_lrs = [group['lr'] for group in optimizer.param_groups]
        print(f"  → LRs: backbone={current_lrs[0]:.2e} | head={current_lrs[1]:.2e}")

        val_acc = accuracy_score(y_true, y_pred)
        f1_macro = f1_score(y_true, y_pred, average="macro", zero_division=0)

        # Top-2 accuracy
        try:
            top2_acc = top_k_accuracy_score(y_true, y_prob, k=2, labels=list(range(NUM_CLASSES)))
        except Exception:
            top2_acc = 0.0

        print(f"Epoch {epoch+1:02d} | "
              f"train_loss={train_loss:.4f} train_acc={train_acc:.4f} | "
              f"val_loss={val_loss:.4f} val_acc={val_acc:.4f} "
              f"top2={top2_acc:.4f} macro_F1={f1_macro:.4f}")

        if f1_macro > best_f1:
            best_f1 = f1_macro
            best_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}
            epochs_no_improve = 0
            print(f" → New best macro F1: {best_f1:.4f}")
        else:
            epochs_no_improve += 1
            print(f" → No improvement for {epochs_no_improve}/{PATIENCE} epochs")

        if epochs_no_improve >= PATIENCE:
            print(f"Early stopping at epoch {epoch+1}")
            break

    # ---------- Final evaluation with best weights ----------
    model.load_state_dict(best_state)
    model.to(DEVICE)
    val_loss, y_pred, y_true, y_prob, video_paths = evaluate(model, val_loader, criterion)

    acc = accuracy_score(y_true, y_pred)
    precision_macro = precision_score(y_true, y_pred, average="macro", zero_division=0)
    recall_macro    = recall_score(y_true, y_pred, average="macro", zero_division=0)
    f1_macro        = f1_score(y_true, y_pred, average="macro", zero_division=0)
    f1_weighted     = f1_score(y_true, y_pred, average="weighted", zero_division=0)

    try:
        top2_acc = top_k_accuracy_score(y_true, y_prob, k=2, labels=list(range(NUM_CLASSES)))
    except Exception:
        top2_acc = 0.0

    try:
        y_true_bin = label_binarize(y_true, classes=list(range(NUM_CLASSES)))
        auc_macro = roc_auc_score(y_true_bin, y_prob, average="macro", multi_class="ovr")
    except Exception as e:
        print(f"AUC calculation warning: {e}")
        auc_macro = 0.0

    accuracy_scores.append(acc)
    top2_scores.append(top2_acc)
    f1_macro_scores.append(f1_macro)
    f1_weighted_scores.append(f1_weighted)
    precision_scores.append(precision_macro)
    recall_scores.append(recall_macro)
    auc_scores.append(auc_macro)

    cm = confusion_matrix(y_true, y_pred)
    confusion_matrices.append(cm)
    plot_cm(cm, f"Activity Recognition CM – Fold {fold}")

    print(f"\n{'='*60}")
    print(f"Fold {fold} Final Metrics:")
    print(f"{'='*60}")
    print(f"Accuracy        : {acc:.4f}")
    print(f"Top-2 Accuracy  : {top2_acc:.4f}")
    print(f"Precision (Macro): {precision_macro:.4f}")
    print(f"Recall (Macro)  : {recall_macro:.4f}")
    print(f"F1-Score (Macro): {f1_macro:.4f}")
    print(f"F1-Score (Weighted): {f1_weighted:.4f}")
    print(f"AUC (Macro OVR) : {auc_macro:.4f}")
    print(f"{'='*60}")

    print(f"\nFold {fold} Classification Report:")
    print(classification_report(y_true, y_pred, target_names=CLASSES_LIST, digits=4, zero_division=0))

    # ========== SAVE EXCEL ==========
    true_class_names = [full_dataset_for_split.idx_to_class[i] for i in y_true]
    pred_class_names = [full_dataset_for_split.idx_to_class[i] for i in y_pred]

    df = pd.DataFrame({
        "Video_Path": video_paths,
        "True_Class": true_class_names,
        "Predicted_Class": pred_class_names,
        "Correct": [t == p for t, p in zip(true_class_names, pred_class_names)]
    })

    excel_path = os.path.join(SAVE_DIR, f"predictions_fold_{fold}.xlsx")
    df.to_excel(excel_path, index=False)
    print(f"Excel saved → {excel_path}")

    # ---------- Save model ----------
    fold_save_path = os.path.join(SAVE_DIR, f"best_hiera_activity_fold_{fold}.pth")
    torch.save({
        "model_state_dict": best_state,
        "fold": fold,
        "macro_f1": best_f1,
        "accuracy": acc,
        "top2_accuracy": top2_acc,
        "class_to_idx": full_dataset_for_split.class_to_idx,
        "idx_to_class": full_dataset_for_split.idx_to_class,
        "classes": CLASSES_LIST,
    }, fold_save_path)
    print(f"Model saved → {fold_save_path}")

    if best_f1 > overall_best_f1:
        overall_best_f1 = best_f1
        overall_best_path = fold_save_path

    del optimizer, scaler, model
    torch.cuda.empty_cache()
    fold += 1


