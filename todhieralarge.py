class ActivityDataset(Dataset):
    def __init__(self, data_dir, classes_list, num_frames=16, size=224, is_train=True):
        self.samples = []
        self.labels = []
        self.num_frames = num_frames
        self.size = size
        self.is_train = is_train
        self.class_to_idx = {cls: idx for idx, cls in enumerate(classes_list)}
        self.idx_to_class = {idx: cls for cls, idx in self.class_to_idx.items()}
        self.augment = VideoAugmentation(size=size, is_train=is_train)

        for class_name in classes_list:
            class_path = Path(data_dir) / class_name
            if not class_path.is_dir():
                print(f"Warning: folder not found → {class_path}")
                continue

            count = 0
            for video_file in sorted(class_path.glob("*")):
                if video_file.suffix.lower() in {".mp4", ".avi", ".mov", ".mkv"}:
                    self.samples.append(str(video_file))
                    self.labels.append(self.class_to_idx[class_name])
                    count += 1
            print(f"Loaded {count} videos from '{class_name}'")

        self.labels = np.array(self.labels)
        print(f"\nTotal videos: {len(self.samples)}")
        print("Class distribution:", dict(Counter(self.labels)))

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        path = self.samples[idx]
        label = self.labels[idx]
        frames = load_video_frames_raw(path, self.num_frames)

        if frames is None:
            # fallback black clip
            frames = [np.zeros((self.size, self.size, 3), dtype=np.uint8)
                      for _ in range(self.num_frames)]

        video_tensor = self.augment(frames)   # (T, C, H, W)
        return video_tensor, label, path


def collate_fn(batch):
    videos, labels, paths = zip(*batch)
    videos = torch.stack(videos)
    labels = torch.tensor(labels, dtype=torch.long)
    return videos, labels, list(paths)


